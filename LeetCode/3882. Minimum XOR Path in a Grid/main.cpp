int minCost(std::vector<std::vector<int>>& grid) 
{
    int n = grid[0].size();
    std::vector<std::bitset<1024>> dp(n);
    dp[0][0] = 1;

    
    for(auto& row:grid)
    {
        for(int j=0;j<n;++j)
        {
            std::bitset<1024> reach;
            if(j==0)
            {
                reach = dp[j];
            }
            else
            {
                reach = dp[j] | dp[j-1];
            }
            dp[j].reset();
            for(int k=0;k<1024;++k)
            {
                if(reach[k])
                {
                    dp[j][k^row[j]]=1;
                }
            }
        }
    }

    int answer=0;
    while(!dp[n-1][answer])
    {
        ++answer;
    }

    return answer;
}

